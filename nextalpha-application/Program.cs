using NETWebAppMVC.Repositories;
using NETWebAppMVC.Repositories.Interfaces;
using NETWebAppMVC.Services;
using NETWebAppMVC.Services.Interfaces;

var builder = WebApplication.CreateBuilder(args);

// Add services to the container.
builder.Services.AddControllers(options =>
{
    // Keep the existing lenient body contract for the placeholder endpoints:
    // without this, [ApiController] would treat every non-nullable reference
    // property (e.g. Product.Name) as [Required] and start returning 400s.
    options.SuppressImplicitRequiredAttributeForNonNullableReferenceTypes = true;
});
builder.Services.AddProblemDetails();
builder.Services.AddHealthChecks();
builder.Services.AddOpenApi();

builder.Services.AddSingleton<IProductRepository, ProductRepository>();
builder.Services.AddScoped<IBusinessLogic, BusinessLogic>();

var app = builder.Build();

// Configure the HTTP request pipeline.
if (app.Environment.IsDevelopment())
{
    // OpenAPI document is generated by Microsoft.AspNetCore.OpenApi; the path is kept at the
    // Swashbuckle-era URL so existing tooling keeps working. Swagger UI is served at /swagger.
    app.MapOpenApi("/swagger/{documentName}/swagger.json");
    app.UseSwaggerUI(options => options.SwaggerEndpoint("/swagger/v1/swagger.json", "NextAlpha API v1"));
}
else
{
    // Unhandled exceptions become RFC 7807 ProblemDetails responses (via AddProblemDetails).
    app.UseExceptionHandler();
    // The default HSTS value is 30 days. You may want to change this for production scenarios, see https://aka.ms/aspnetcore-hsts.
    app.UseHsts();
}

// Empty 4xx/5xx responses (e.g. unknown routes) also get a ProblemDetails body.
app.UseStatusCodePages();

app.UseHttpsRedirection();

app.UseAuthorization();

app.MapHealthChecks("/health");
app.MapControllers();

app.Run();

